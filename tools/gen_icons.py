#!/usr/bin/env python3
# Persona icon pipeline: game-icons.net SVGs -> 1-bpp 80x80 C bitmaps
# -> src/persona_art.h. Icons are black-on-white, content auto-cropped.
# Re-run after swapping any SVG in /tmp/opencode/icons (or a new icons dir).
from PIL import Image, ImageDraw, ImageFont
import cairosvg, io, os

ICON_DIR = "/tmp/opencode/icons"
OUT_H = "src/persona_art.h"
FILES = ["prince.svg", "princess.svg", "dragon.svg", "wizard.svg", "frog.svg", "robot.svg"]
NAMES = ["Prince", "Princess", "Dragon", "Wizard", "Frog", "Robot"]
SIZE = 80  # bitmap box (width % 8 == 0)

def bitmap(svg):
    png = cairosvg.svg2png(url=f"{ICON_DIR}/{svg}", output_width=512, output_height=512,
                           background_color="white")
    im = Image.open(io.BytesIO(png)).convert("L").point(lambda p: 0 if p < 250 else 255)
    # crop to ink bounding box
    bbox = im.point(lambda p: 255 - p).getbbox()  # ink = dark
    im = im.crop(bbox)
    # fit into SIZE-6 box, keep aspect
    s = (SIZE - 6) / max(im.size)
    im = im.resize((max(1, int(im.width * s)), max(1, int(im.height * s))))
    out = Image.new("L", (SIZE, SIZE), 255)
    out.paste(im, ((SIZE - im.width) // 2, (SIZE - im.height) // 2))
    return out

rows = []
for f in FILES:
    im = bitmap(f)
    ink = im.point(lambda p: 255 - p)
    bbox = ink.getbbox()  # ink bounding box (sanity check)
    bits = list(im.getdata())  # row-major, 0 = ink
    nbytes_row = SIZE // 8
    b = bytearray(nbytes_row * SIZE)
    for i, px in enumerate(bits):
        if px == 0:  # ink
            b[i // 8] |= 0x80 >> (i % 8)
    rows.append(b)
    im.save(f"docs/mockups/icon_{f.split('.')[0]}_80.png")  # preview of what device will draw
    print(f"{f}: ink bbox {bbox}")

with open(OUT_H, "w") as h:
    h.write("""// Generated by tools/gen_icons.py — persona icons from game-icons.net
// (CC-BY 3.0: "crown"/"queen-crown"/"dragon-head" by Lorc,
// "wizard-face"->"pointy-hat"/"frog-prince"/"unicorn" by Delapouite/Unicon).
// 1-bpp, 80x80, row-major, 1 = ink... stored 0-bit = ink per Adafruit drawBitmap.
#pragma once
#include <Arduino.h>

namespace persona_art {
""")
    for name, b in zip(NAMES, rows):
        h.write(f"// {name}\n")
        h.write(f"static const uint8_t k{name}[{len(b)}] PROGMEM = {{\n")
        for r in range(SIZE):
            row = b[r * (SIZE // 8):(r + 1) * (SIZE // 8)]
            h.write("  " + ", ".join(f"0x{x:02X}" for x in row) + ",\n")
        h.write("};\n\n")
    h.write("}  // namespace persona_art\n")
print(f"wrote {OUT_H}")
